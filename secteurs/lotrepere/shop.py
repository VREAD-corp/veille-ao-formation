def plan_radios(site) -> str:
    """input[name="product"] radios (no id), shared by the card form and the quote form. The 12-month radio
    carries arm a; its data-arm-b, data-price-b and data-per-b let checkout/xp-price.js switch it to arm b."""
    p = site.sales.products
    a, b = PLAN_ARMS["a"], PLAN_ARMS["b"]
    twelve = (f'<label class="plan"><input type="radio" name="product" value="{a}" data-arm-a="{a}" data-arm-b="{b}" checked> '
              f'<span><strong>12 mois</strong> — <span data-price-for="{a}" data-price-a="{e(price_label(p[a]))}" '
              f'data-price-b="{e(price_label(p[b]))}">{e(price_label(p[a]))}</span>'
              f'<br><span class="muted">soit <span class="xp-price" data-a="{e(per_month(p[a], 12))}" data-b="{e(per_month(p[b], 12))}">'
              f'{e(per_month(p[a], 12))}</span> par mois, payé une fois, sans renouvellement automatique</span></span></label>')
    three = (f'<label class="plan"><input type="radio" name="product" value="lot-repere-3m"> '
             f'<span><strong>3 mois</strong> — <span data-price-for="lot-repere-3m">{e(price_label(p["lot-repere-3m"]))}</span>'
             f'<br><span class="muted">soit {e(per_month(p["lot-repere-3m"], 3))} par mois, payé une fois, sans renouvellement automatique</span></span></label>')
    return twelve + three


