def product_jsonld(site, organization: dict) -> list[dict]:
    """schema.org Product with one Offer per prepaid period (prices from sales.config.json), sold by the hub
    Organization (referenced by @id, not repeated)."""
    p = site.sales.products
    url = site.url + "alertes/"
    # E-mail service starting on payment (first alert the next morning), French businesses only; B2B sale without
    # withdrawal right (CGV art. 10): free "shipping" to FR, returns not permitted.
    shipping = {"@type": "OfferShippingDetails",
                "shippingRate": {"@type": "MonetaryAmount", "value": "0", "currency": "EUR"},
                "shippingDestination": {"@type": "DefinedRegion", "addressCountry": "FR"},
                "deliveryTime": {"@type": "ShippingDeliveryTime",
                                 "handlingTime": {"@type": "QuantitativeValue", "minValue": 0, "maxValue": 1, "unitCode": "DAY"},
                                 "transitTime": {"@type": "QuantitativeValue", "minValue": 0, "maxValue": 0, "unitCode": "DAY"}}}
    returns = {"@type": "MerchantReturnPolicy", "applicableCountry": "FR",
               "returnPolicyCategory": "https://schema.org/MerchantReturnNotPermitted",
               "merchantReturnLink": site.url + "cgv-pro/"}
    offers = [{"@type": "Offer", "name": f"{months} mois", "price": schema_price(p[pid]), "priceCurrency": "EUR",
               "availability": "https://schema.org/InStock", "url": url, "seller": {"@id": organization["@id"]},
               "shippingDetails": shipping, "hasMerchantReturnPolicy": returns}
              for pid, months in (("veille-ao-3m", 3), ("veille-ao-12m", 12))]
    return [
        {"@context": "https://schema.org", "@type": "Product", "name": PRODUCT_NAME,
         "description": "Chaque matin, par e-mail, les nouveaux appels d'offres publics de formation (BOAMP, TED) "
                        "correspondant à vos régions, mots-clés et familles CPV, avec la date limite et le lien vers "
                        "l'avis officiel. Période prépayée de 3 ou 12 mois, sans renouvellement automatique. "
                        "Réservé aux professionnels.",
         "image": site.url + "static/og.png", "url": url,
         "brand": {"@type": "Brand", "name": "Veille AO Formation"}, "sku": PRODUCT_SKU, "offers": offers},
    ]


def plan_radios(site) -> str:
    """input[name="product"] radios (no id), shared by the card form and the quote form."""
    p = site.sales.products
    plans = []
    for pid, months, checked in (("veille-ao-12m", 12, True), ("veille-ao-3m", 3, False)):
        plans.append(
            f'<label class="plan"><input type="radio" name="product" value="{pid}"{" checked" if checked else ""}> '
            f'<span><strong>{months} mois</strong> — <span data-price-for="{pid}">{e(price_label(p[pid]))}</span>'
            f'<br><span class="muted">soit {e(per_month(p[pid], months))} par mois, payé une fois, sans renouvellement automatique</span></span></label>')
    return "".join(plans)


