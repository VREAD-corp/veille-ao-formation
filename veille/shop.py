def e(text: object) -> str:
    return escape("" if text is None else str(text), quote=True)


def per_month(cents: int, months: int) -> str:
    return eur(round(cents / months))


VAT_NOTE = "TVA non applicable, art. 293 B du CGI"
PRODUCT_NAME = "Alertes e-mail appels d'offres formation"
PRODUCT_SKU = "veille-ao-alertes"


def price_label(cents: int) -> str:
    return f"{eur(cents)} net ({VAT_NOTE})"


# « Commander » button; {prix} = the price, same format as pay.js (« Payer 149 € et activer mes alertes »).
PAY_LABEL = "Payer {prix} et activer mes alertes"
DEFAULT_PLAN = "veille-ao-12m"


def pay_button_text(cents: int) -> str:
    whole = cents % 100 == 0
    s = str(cents // 100) if whole else f"{cents / 100:.2f}".replace(".", ",")
    return PAY_LABEL.replace("{prix}", s + "\u00a0€")


def copy_assets(site) -> None:
    out = site.out / "checkout"
    out.mkdir(parents=True, exist_ok=True)
    for f in ("pay.js", "devis.js", "order.js", "alerts-form.js"):
        shutil.copyfile(CHECKOUT / f, out / f)
    shutil.copyfile(STRIPE_LAZY, out / "stripe-lazy.js")
    s = site.sales
    cfg = {
        "endpoint": s.endpoint,
        "publishableKey": s.publishable_key,
        "product": DEFAULT_PLAN,
        # Static prices: pay.js mounts the Payment Element as soon as it runs (display only; the Apps Script catalog
        # stays the price authority and refuses a different expectedAmount).
        "offers": {pid: {"amount": cents} for pid, cents in s.products.items()},
        "currency": "eur",
        "termsVersion": TERMS_VERSION,
        "payLabel": PAY_LABEL,
        "termsUrl": site.link("cgv-pro/"),
        "quotesEnabled": s.quotes_enabled,
        "orderPage": "commande.html",
        "laterText": "Si vous fermez cette page, votre abonnement est tout de même activé automatiquement "
                     "dans les 10 minutes, avec l'e-mail de bienvenue et la facture.",
    }
    (out / "checkout-config.js").write_text(
        "// Generated by the site build from sales.config.json. Public by design.\n"
        f"window.OCTAVE_PAY = {json.dumps(cfg, ensure_ascii=False)};\n", encoding="utf-8")


